import { readFile, writeFile } from 'node:fs/promises';
const files = [
  ['environment/studio-small-09-1k.hdr', 'application/octet-stream'],
  ['materials/brown-leather-color.jpg', 'image/jpeg'],
  ['materials/brown-leather-normal.jpg', 'image/jpeg'],
  ['materials/brown-leather-roughness.jpg', 'image/jpeg'],
  ['models/atelier-tote.glb', 'model/gltf-binary'],
  ['models/atelier-shoulder.glb', 'model/gltf-binary'],
];
const entries = await Promise.all(files.map(async ([name, mime]) => [
  `/assets/${name}`, { mime, base64: (await readFile(new URL(`../public/assets/${name}`, import.meta.url))).toString('base64') },
]));
await writeFile(new URL('../src/chatgpt/inlineAssets.generated.ts', import.meta.url),
  `// Generated by scripts/build-mcp-assets.mjs. No credentials or network URLs.\nexport default ${JSON.stringify(Object.fromEntries(entries))};\n`);
console.log(`Bundled ${entries.length} local 3D assets for the conversation preview.`);
